"""Generate scripts/m2/engine_paths.txt: the engine-destined file set that gate G8 checks.

  scripts/m2/gen_engine_paths.py > scripts/m2/engine_paths.txt
  scripts/m2/gen_engine_paths.py --check      # exit 1 if the committed file is stale

The set is the files already in Engine/ plus every plugin file still to move into the engine
(InternalAWSCognitoAuth). Files that are split rather than moved (the engine halves of Support/Helpers,
Support/HostedUI and Support/CustomEndpoint) are listed with a leading `?`: G8 reports them but does not
enforce the engine rules on them until the split lands. Paths are relative to the repository root.
Regenerate whenever a change moves or adds files; the list is a reviewed input, not something G8 infers.
Every listed directory and file must exist, so the change that moves one also drops it from the lists below.
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
PLUGIN = "AmplifyPlugins/Auth/Sources/AWSCognitoAuthPlugin"
ENGINE = "AmplifyClients/Internal/InternalAWSCognitoAuth/Sources"

# Directories that move whole, with the files kept back in the plugin. All of StateMachine/, Actions/
# (Action+Logging included) and ASF/ has moved, so they are listed from Engine/.
MOVED_DIRECTORIES = {
    "CredentialStorage": ["CredentialStorage/AmplifyCredentials+CognitoSession.swift"],
    "Service": [
        "Service/ErrorMapping/AuthErrorConvertible.swift",        # the plugin keeps the protocol
        "Service/SdkTypealiases.swift",                           # public `NetworkResult` (no public type moves)
        "Service/Helpers/ListDevicesOutputResponse+Helper.swift",  # glue, builds `AWSAuthDevice`
    ],
}
# Single files to move. Files already moved (Support/Constants, Models/AuthChallengeType.swift) are listed
# from Engine/ and must not be repeated here.
MOVED_FILES = []
# Directories whose engine halves move after a split: reported, not enforced. The engine halves of
# Support/Helpers and Support/HostedUI, and all of Support/CustomEndpoint, have moved; what is left in the
# plugin there is glue.
SPLIT_DIRECTORIES = []


def require(relative_path, kind):
    """Every listed path must exist: a typo or a stale entry fails instead of silently listing nothing."""
    check = os.path.isdir if kind == "directory" else os.path.isfile
    if not check(os.path.join(ROOT, relative_path)):
        sys.exit(f"listed {kind} is missing: {relative_path}")
    return relative_path


def swift_files(relative_directory):
    base = os.path.join(ROOT, require(relative_directory, "directory"))
    found = []
    for directory, _, files in os.walk(base):
        for name in files:
            if name.endswith(".swift"):
                found.append(os.path.relpath(os.path.join(directory, name), ROOT))
    return sorted(found)


def generate():
    lines = [
        "# Engine-destined files for gate G8 (scripts/m2/error_match_gate.sh).",
        "# Generated by scripts/m2/gen_engine_paths.py; do not edit by hand. `?` = moves after a split.",
    ]
    lines += swift_files(ENGINE)
    plugin_files = []
    for directory, kept in MOVED_DIRECTORIES.items():
        kept_paths = {require(os.path.join(PLUGIN, path), "file") for path in kept}
        plugin_files += [path for path in swift_files(os.path.join(PLUGIN, directory)) if path not in kept_paths]
    for path in MOVED_FILES:
        plugin_files.append(require(os.path.join(PLUGIN, path), "file"))
    lines += sorted(plugin_files)
    for directory in SPLIT_DIRECTORIES:
        scheduled = {os.path.join(PLUGIN, path) for path in MOVED_FILES}
        lines += ["?" + path for path in swift_files(os.path.join(PLUGIN, directory)) if path not in scheduled]
    return "\n".join(lines) + "\n"


def main():
    text = generate()
    if "--check" in sys.argv:
        with open(os.path.join(ROOT, "scripts/m2/engine_paths.txt")) as committed:
            if committed.read() != text:
                sys.exit("scripts/m2/engine_paths.txt is stale; regenerate it with scripts/m2/gen_engine_paths.py")
        print("engine_paths.txt is current")
        return
    sys.stdout.write(text)


if __name__ == "__main__":
    main()
