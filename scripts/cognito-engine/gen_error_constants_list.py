"""Regenerate the list of AuthPluginErrorConstants members that ErrorCatalogueSnapshotTests snapshots.

Usage:
  scripts/cognito-engine/gen_error_constants_list.py > \\
    AmplifyPlugins/Auth/Tests/AWSCognitoAuthPluginUnitTests/GoldenTests/ErrorCatalogueConstants.swift

The test also re-parses the constants file at run time and fails if a member is missing from the list,
so a new constant cannot silently escape the snapshot. The constants file is looked up in the plugin
and, once it has moved, in the engine.
"""
import os
import re
import sys

CANDIDATES = [
    "AmplifyPlugins/Auth/Sources/AWSCognitoAuthPlugin/Support/Constants/AuthPluginErrorConstants.swift",
    "AmplifyClients/Internal/InternalAWSCognitoAuth/Sources/Support/Constants/AuthPluginErrorConstants.swift",
]
DECL = re.compile(
    r"^\s*static let ([A-Za-z0-9_]+): "
    r"(AuthPluginErrorString|AuthPluginValidationErrorString|RecoverySuggestion)\b"
)
KINDS = {
    "AuthPluginErrorString": "pair",
    "AuthPluginValidationErrorString": "validation",
    "RecoverySuggestion": "suggestion",
}


def main():
    root = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
    path = next((os.path.join(root, c) for c in CANDIDATES if os.path.exists(os.path.join(root, c))), None)
    if path is None:
        sys.exit("AuthPluginErrorConstants.swift not found")

    rows = []
    with open(path) as f:
        for line in f:
            m = DECL.match(line)
            if m:
                rows.append(m.groups())

    out = [
        "//",
        "// Copyright Amazon.com Inc. or its affiliates.",
        "// All Rights Reserved.",
        "//",
        "// SPDX-License-Identifier: Apache-2.0",
        "//",
        "",
        "// Generated by scripts/cognito-engine/gen_error_constants_list.py. Do not edit by hand.",
        "",
        "@testable import AWSCognitoAuthPlugin",
        "import InternalAWSCognitoAuth",
        "",
        "extension ErrorCatalogueSnapshotTests {",
        "",
        "    /// Every `AuthPluginErrorConstants` member, in declaration order.",
        "    static var errorConstants: [(name: String, value: ErrorConstantValue)] {",
        "        [",
    ]
    for name, typ in rows:
        out.append(f'            ("{name}", .{KINDS[typ]}(AuthPluginErrorConstants.{name})),')
    out += ["        ]", "    }", "}", ""]
    sys.stdout.write("\n".join(out))
    print(f"{len(rows)} members from {os.path.relpath(path, root)}", file=sys.stderr)


if __name__ == "__main__":
    main()
